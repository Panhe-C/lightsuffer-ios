import Foundation

/// Namespace for the pure-Swift physical film engine.
///
/// The engine is a port of the Python engine of *spektrafilm* by
/// Andrea Volpato (<https://github.com/andreavolpato/spektrafilm>).
/// The port is validated tap by tap against the reference fixtures that are
/// generated by ``tools/gen_fixtures.py`` and
/// ``tools/gen_autoexposure_fixtures.py`` from the upstream Python code.
public enum FilmPhysics {

    /// Semantic version of the Swift port.
    public static let version = "0.1.0"

    /// Upstream project this engine is a port of.
    public static let upstreamProject = "spektrafilm"

    /// Upstream URL.
    public static let upstreamURL = "https://github.com/andreavolpato/spektrafilm"

    /// Upstream commit the reference fixtures were generated from.
    public static let upstreamCommit = "3bb2c2d"

    /// Credit shown in the app: 「film modeling powered by spektrafilm」.
    public static let credit = "film modeling powered by spektrafilm"

    // MARK: - bundled resources

    /// The bundle that carries the bundled film / print profiles.
    ///
    /// The profiles are unmodified copies of the spektrafilm profile data
    /// (CC BY-SA 4.0, see `SPEKTRAFILM_LICENSE.txt`).
    public static var resourcesBundle: Bundle { Bundle.module }

    /// Location of a bundled profile JSON file, e.g. `kodak_portra_400`.
    public static func profileURL(stock: String) -> URL? {
        resourcesBundle.url(forResource: stock, withExtension: "json", subdirectory: "profiles")
            ?? resourcesBundle.url(forResource: stock, withExtension: "json")
    }

    /// Location of any file bundled next to the profiles (e.g. `CHANGELOG.txt`).
    public static func profileResourceURL(name: String, extension ext: String) -> URL? {
        resourcesBundle.url(forResource: name, withExtension: ext, subdirectory: "profiles")
            ?? resourcesBundle.url(forResource: name, withExtension: ext)
    }

    /// The stock names of the profiles that ship with this package.
    ///
    /// The package bundles the complete upstream catalogue: the 20 camera
    /// films and the 8 print media (see ``StockCatalog``).
    public static let bundledProfiles = StockCatalog.stockNames

    /// The spectral sampling of the upstream engine: 380…780 nm in 5 nm steps.
    ///
    /// Upstream reference: `spektrafilm.config.SPECTRAL_SHAPE`
    /// (`colour.SpectralShape(380, 780, 5)`).
    public static let wavelengths: [Double] = Array(
        stride(from: 380.0, through: 780.0, by: 5.0)
    )

    /// Location of a bundled resource of the package.
    ///
    /// - Parameters:
    ///   - name: the name of the resource, without its extension.
    ///   - extension: the extension of the resource.
    public static func resourceURL(named name: String, extension ext: String) -> URL? {
        for subdirectory in [nil, "spectral", "filters", "profiles"] {
            if let url = resourcesBundle.url(
                forResource: name, withExtension: ext, subdirectory: subdirectory
            ) {
                return url
            }
        }
        for root in [resourcesBundle.resourceURL, resourcesBundle.bundleURL].compactMap({ $0 }) {
            guard let enumerator = FileManager.default.enumerator(
                at: root, includingPropertiesForKeys: nil
            ) else { continue }
            for case let url as URL in enumerator
            where url.lastPathComponent == "\(name).\(ext)" {
                return url
            }
        }
        return nil
    }
}
